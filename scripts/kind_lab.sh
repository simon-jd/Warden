#!/usr/bin/env bash
# Throwaway kind cluster for the live Kubernetes tests (Task 14 IsolatePod /
# CordonNode, Task 9 JIT RoleBindings). One node, named warden-respond, on its
# own Docker network (warden-kind) and with the project-local kubeconfig
# .cache/kind/kubeconfig; ~/.kube/config is never read or written.
#
#   scripts/kind_lab.sh run <command...>   up, run the command, always down
#   scripts/kind_lab.sh up | down
#   scripts/kind_lab.sh up --audit | status --audit | check-empty --audit | down --audit | config --audit
#
# The node image is pinned by digest (the one kind v0.33.0 publishes for
# v1.34.11). Pod images are loaded from the local Docker image store; nothing
# is pulled inside the cluster (pods use imagePullPolicy: Never).
#
# --audit: the audit lab of Task 13's Kubernetes round (docs/falco-detector.md;
# make kind-audit-up / kind-audit-status / kind-audit-down), a cluster of its
# own beside warden-respond, which it leaves alone. One node,
# warden-lab-control-plane, cluster warden-lab, on its own network
# warden-kind-lab; kubeconfig .cache/kind-warden-lab/kubeconfig and its JSON
# export kubeconfig.json (context kind-warden-lab, loopback API server,
# embedded certificates: what attacks/stratus/emulate.py checks; it holds the
# lab's admin credentials, mode 0600), and the namespace warden-lab, labelled
# project=warden and owner=warden-lab, in which the wrapper runs Stratus.
# kube-apiserver logs every request by
# detect/falco/k8s-audit-policy.yaml into .cache/kind-warden-lab/audit/audit.log:
# format json, mode blocking (each event is written before the request
# returns; no batching), maxsize 1024 MB so a session never rotates. This
# user creates the log before the cluster, so the API server (root in the
# node) appends to a file the k8saudit instance's collector can read without
# root; an earlier lab's log is renamed, never overwritten. The node container
# is moved to CPUs 0-7,16-31 (WARDEN_LAB_CPUSET) as soon as Docker has it, and
# up fails if it is not there: kind has no cpuset option. The pod image the
# lab's runs use (.tools/stratus/images, pinned by digest) is loaded and also
# named by its digest, so a pod that names the digest starts without a pull.
# check-empty --audit (scripts/kind_audit_check.py) exits 0 only if warden-lab
# holds nothing but what Kubernetes puts in every namespace: call it before
# each run, because the audit importer's namespace match ignores who made a
# request. down --audit deletes the cluster, its network, kubeconfigs and
# generated files, and keeps only the audit logs (data, as the detector keeps
# its own).
set -euo pipefail
root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
kind=$root/.tools/kind/kind
name=warden-respond
kubeconfig=$root/.cache/kind/kubeconfig
node_image=kindest/node:v1.34.11@sha256:44e222ee2132dab25ff87301682f89eb82c7880ea3a1bf543bfe9708fd08d67d
pod_images=(python:3.14.4-alpine)
export KIND_EXPERIMENTAL_DOCKER_NETWORK=warden-kind

kubectl=$root/.tools/kubectl/kubectl
cpuset=${WARDEN_LAB_CPUSET:-0-7,16-31}
audit_name=warden-lab
audit_node=warden-lab-control-plane
audit_network=warden-kind-lab
audit_dir=$root/.cache/kind-warden-lab
audit_policy=$root/detect/falco/k8s-audit-policy.yaml
# <archive in .tools/stratus/images>=<image name>=<the archive's linux/amd64 manifest digest>
audit_images=(
  busybox-1.37.0.oci.tar=docker.io/library/busybox:1.37.0=sha256:66a6306db78bf2dbf3487f293aa8d6990d8e506fdffab9cc43fe422becf886e4
)
# The namespace attacks/stratus/emulate.py requires (guard_namespace).
audit_namespace='{"apiVersion":"v1","kind":"Namespace","metadata":{"name":"warden-lab","labels":{"project":"warden","owner":"warden-lab"}}}'

up() {
  [[ -x $kind ]] || "$root/scripts/restore-tools.sh" kind
  mkdir -p "$(dirname "$kubeconfig")"
  "$kind" create cluster --name "$name" --kubeconfig "$kubeconfig" --image "$node_image" --wait 180s
  # `kind load docker-image` fails on multi-platform images whose other
  # platforms are not in the local store, so load a linux/amd64-only archive.
  local archive=$root/.cache/kind/images.tar
  for img in "${pod_images[@]}"; do
    docker save --platform linux/amd64 -o "$archive" "$img"
    "$kind" load image-archive "$archive" --name "$name"
    rm -f "$archive"
  done
}

down() {
  "$kind" delete cluster --name "$name" --kubeconfig "$kubeconfig" || true
  # kind creates the network on first use; remove it only if no container is left on it.
  if docker network inspect warden-kind >/dev/null 2>&1; then
    docker network rm warden-kind >/dev/null || echo "warden-kind network still in use; left in place" >&2
  fi
  rm -f "$kubeconfig"
}

audit_config() {
  cat <<EOF
# Generated by scripts/kind_lab.sh up --audit.
kind: Cluster
apiVersion: kind.x-k8s.io/v1alpha4
nodes:
- role: control-plane
  kubeadmConfigPatches:
  - |
    kind: ClusterConfiguration
    apiServer:
      extraArgs:
        audit-policy-file: /etc/kubernetes/policies/audit-policy.yaml
        audit-log-path: /var/log/kubernetes/audit/audit.log
        audit-log-format: json
        audit-log-mode: blocking
        audit-log-maxsize: "1024"
        audit-log-maxbackup: "1"
      extraVolumes:
      - name: audit-policies
        hostPath: /etc/kubernetes/policies
        mountPath: /etc/kubernetes/policies
        readOnly: true
        pathType: Directory
      - name: audit-logs
        hostPath: /var/log/kubernetes/audit
        mountPath: /var/log/kubernetes/audit
        readOnly: false
        pathType: Directory
  extraMounts:
  - hostPath: $audit_dir/policy
    containerPath: /etc/kubernetes/policies
    readOnly: true
  - hostPath: $audit_dir/audit
    containerPath: /var/log/kubernetes/audit
EOF
}

# Directories whose mode alone says who may open them (a parent's default
# ACL would otherwise be inherited).
private_dirs() {
  mkdir -p "$@"
  python3 -I -c '
import os, sys
for path in sys.argv[1:]:
    for name in ("system.posix_acl_access", "system.posix_acl_default"):
        try:
            os.removexattr(path, name)
        except OSError:
            pass
    os.chmod(path, 0o700)' "$@"
}

audit_up() {
  [[ -x $kind ]] || "$root/scripts/restore-tools.sh" kind
  [[ -x $kubectl ]] || "$root/scripts/restore-tools.sh" kubectl
  [[ -f $root/.tools/stratus/.complete ]] || "$root/scripts/restore-tools.sh" stratus
  if "$kind" get clusters 2>/dev/null | grep -qx "$audit_name" || docker container inspect "$audit_node" >/dev/null 2>&1; then
    echo "kind cluster $audit_name already exists; run $0 down --audit first" >&2
    exit 1
  fi
  private_dirs "$audit_dir" "$audit_dir/audit" "$audit_dir/policy"
  install -m 0644 "$audit_policy" "$audit_dir/policy/audit-policy.yaml"
  local log=$audit_dir/audit/audit.log
  if [[ -e $log ]]; then
    mv "$log" "$audit_dir/audit/audit-$(date -u +%Y%m%dT%H%M%SZ).log"
  fi
  install -m 0600 /dev/null "$log"
  audit_config >"$audit_dir/kind-config.yaml"
  (
    for _ in $(seq 1 1200); do
      if docker update --cpuset-cpus "$cpuset" "$audit_node" >/dev/null 2>&1; then exit 0; fi
      sleep 0.1
    done
    exit 1
  ) &
  local pin=$!
  KIND_EXPERIMENTAL_DOCKER_NETWORK=$audit_network taskset -c "$cpuset" "$kind" create cluster --name "$audit_name" \
    --kubeconfig "$audit_dir/kubeconfig" --image "$node_image" --config "$audit_dir/kind-config.yaml" --wait 180s
  wait "$pin" || docker update --cpuset-cpus "$cpuset" "$audit_node" >/dev/null
  local got
  got=$(docker container inspect --format '{{.HostConfig.CpusetCpus}}' "$audit_node")
  if [[ $got != "$cpuset" ]]; then
    echo "$audit_node runs on CPUs '$got', not $cpuset" >&2
    exit 1
  fi
  echo "$audit_node: cpuset $got (docker update --cpuset-cpus $cpuset)"
  local entry archive image digest
  for entry in "${audit_images[@]}"; do
    archive=${entry%%=*}; image=${entry#*=}; digest=${image#*=}; image=${image%%=*}
    "$kind" load image-archive "$root/.tools/stratus/images/$archive" --name "$audit_name"
    docker exec "$audit_node" ctr -n k8s.io images tag --force "$image" "${image%:*}@$digest" >/dev/null
  done
  install -m 0600 /dev/null "$audit_dir/kubeconfig.json"
  "$kubectl" --kubeconfig "$audit_dir/kubeconfig" --context "kind-$audit_name" config view --raw --minify -o json \
    >"$audit_dir/kubeconfig.json"
  "$kubectl" --kubeconfig "$audit_dir/kubeconfig.json" --context "kind-$audit_name" create -f - <<<"$audit_namespace" >/dev/null
  "$kubectl" --kubeconfig "$audit_dir/kubeconfig.json" --context "kind-$audit_name" wait --for=jsonpath='{.status.phase}'=Active \
    namespace/warden-lab --timeout=60s >/dev/null
  echo "kind audit lab up: audit log $log, kubeconfig $audit_dir/kubeconfig.json, namespace warden-lab"
}

audit_status() {
  local state
  state=$(docker container inspect --format '{{.State.Status}} since {{.State.StartedAt}}, cpuset {{.HostConfig.CpusetCpus}}' \
    "$audit_node" 2>/dev/null) || state=absent
  echo "node $audit_node: $state"
  if docker network inspect "$audit_network" >/dev/null 2>&1; then echo "network $audit_network: present"; else echo "network $audit_network: absent"; fi
  if [[ -f $audit_dir/kubeconfig.json ]]; then
    echo "kubeconfig: $audit_dir/kubeconfig.json"
    echo "namespace warden-lab: $("$kubectl" --kubeconfig "$audit_dir/kubeconfig.json" --context "kind-$audit_name" get namespace warden-lab \
      -o jsonpath='{.status.phase} {.metadata.labels}' 2>/dev/null || echo absent)"
  else
    echo "kubeconfig: absent"
  fi
  if [[ -f $audit_dir/audit/audit.log ]]; then
    echo "audit log: $audit_dir/audit/audit.log, $(stat -c %s "$audit_dir/audit/audit.log") bytes"
  else
    echo "audit log: absent"
  fi
}

audit_check_empty() {
  [[ -x $kubectl ]] || "$root/scripts/restore-tools.sh" kubectl
  python3 -I -B "$root/scripts/kind_audit_check.py" --kubectl "$kubectl" --kubeconfig "$audit_dir/kubeconfig.json"
}

audit_down() {
  [[ -x $kind ]] || "$root/scripts/restore-tools.sh" kind
  "$kind" delete cluster --name "$audit_name" --kubeconfig "$audit_dir/kubeconfig" || true
  if docker container inspect "$audit_node" >/dev/null 2>&1; then
    echo "$audit_node is still there after kind delete" >&2
    exit 1
  fi
  if docker network inspect "$audit_network" >/dev/null 2>&1; then
    docker network rm "$audit_network" >/dev/null || { echo "$audit_network network still in use; left in place" >&2; exit 1; }
  fi
  rm -f "$audit_dir/kubeconfig" "$audit_dir/kubeconfig.json" "$audit_dir/kind-config.yaml" "$audit_dir/policy/audit-policy.yaml"
  [[ -d $audit_dir/policy ]] && rmdir "$audit_dir/policy"
  echo "kind audit lab down; audit logs kept in $audit_dir/audit"
}

usage() {
  echo "usage: $0 up|down [--audit] | status --audit | check-empty --audit | config --audit | run <command...>" >&2
  exit 2
}

case "${1:-}" in
  up) if [[ ${2:-} == --audit ]]; then audit_up; else up; fi ;;
  down) if [[ ${2:-} == --audit ]]; then audit_down; else down; fi ;;
  status) [[ ${2:-} == --audit ]] || usage; audit_status ;;
  config) [[ ${2:-} == --audit ]] || usage; audit_config ;;
  check-empty) [[ ${2:-} == --audit ]] || usage; audit_check_empty ;;
  run)
    shift
    [[ $# -gt 0 ]] || { echo "usage: $0 run <command...>" >&2; exit 2; }
    trap down EXIT
    up
    "$@"
    ;;
  *) usage ;;
esac
